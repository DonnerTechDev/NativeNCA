using System.Text;
using System.Xml.Linq;

// Writes the review sheet for translators: every key with its Russian and Kazakh text and the notes kept as
// <comment> in Strings.kk.resx (term choices that need a native speaker's check).
//
//   dotnet run --project tools/LocalizationReview -- docs/localization-review.md

string output = args.Length > 0 ? args[0] : "docs/localization-review.md";
string dir = Path.Combine(FindRepoRoot(), "NativeNCA.Core", "Localization");

var ru = Read(Path.Combine(dir, "Strings.resx"));
var kk = Read(Path.Combine(dir, "Strings.kk.resx")).ToDictionary(p => p.Key, p => p.Value);

var sb = new StringBuilder();
sb.AppendLine("# Kazakh translation review");
sb.AppendLine();
sb.AppendLine("Generated from `NativeNCA.Core/Localization/Strings*.resx` by `tools/LocalizationReview`. Do not edit this file:");
sb.AppendLine("change the `.resx` files (notes are the `<comment>` elements in `Strings.kk.resx`) and run");
sb.AppendLine("`dotnet run --project tools/LocalizationReview -- docs/localization-review.md` again.");
sb.AppendLine();
sb.AppendLine("Conventions: `{0}`, `{1}` are values inserted by the program (versions, names, numbers) and must stay. Keys ending in");
sb.AppendLine("`_Plural` list the forms separated by `|`: Russian has three (1 день, 2 дня, 5 дней), Kazakh one. A non-breaking");
sb.AppendLine("hyphen is used inside words such as «Windows‑тан» so they are not split across lines.");
sb.AppendLine();
sb.AppendLine($"{kk.Count(e => e.Value.Note != null)} of {ru.Count} strings have a note.");
sb.AppendLine();
sb.AppendLine("| Key | Русский | Қазақша | Note |");
sb.AppendLine("| --- | --- | --- | --- |");
foreach (var (key, (text, _)) in ru)
{
    kk.TryGetValue(key, out var translated);
    sb.AppendLine($"| `{key}` | {Cell(text ?? "")} | {Cell(translated.Text ?? "**missing**")} | {Cell(translated.Note ?? "")} |");
}

File.WriteAllText(output, sb.ToString(), new UTF8Encoding(false));
Console.WriteLine($"{ru.Count} strings written to {output}");

static List<KeyValuePair<string, (string? Text, string? Note)>> Read(string path) =>
    XDocument.Load(path).Root!.Elements("data")
        .Select(d => new KeyValuePair<string, (string?, string?)>(
            (string)d.Attribute("name")!, ((string?)d.Element("value"), (string?)d.Element("comment"))))
        .ToList();

static string Cell(string text) => text.Replace("\r\n", "\n").Replace("|", "\\|").Replace("\n", "<br>");

static string FindRepoRoot()
{
    var dir = new DirectoryInfo(Directory.GetCurrentDirectory());
    while (dir != null && !File.Exists(Path.Combine(dir.FullName, "NativeNCA.slnx"))) dir = dir.Parent;
    return dir?.FullName ?? throw new DirectoryNotFoundException("Run from inside the repository");
}
